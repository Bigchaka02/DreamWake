"""Measure which canned dreams pass the dreaming store's practice control."""
import argparse
import json
import os
import sys
from pathlib import Path

if __name__ == "__main__" and not __package__:
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from dreamwake import designs, llm, run, tasks

TASK = "settings_gen"
DECISION = "every duration setting is now stored in milliseconds, and its name ends in _MS"
ITEMS = [
    {"kind": "rule", "text": "Every duration setting is stored in milliseconds and its name ends in _MS."},
    {"kind": "rule", "text": "Settings are defined in settings.tmpl.json; src/settings.py is generated by "
                             "tools/gen.py - never edit it by hand."},
    {"kind": "rule", "text": "Every new or renamed setting must be listed in CHANGES.md, or tools/audit.py fails."},
]
CASES = {
    "good": ("Add a setting for how long to wait before retrying a failed upload, 5 seconds.", ["_MS"], []),
    "wrong_scope": ("Add a setting for the maximum number of items kept in the cache, 200.", ["_MS"], []),
    "wrong_scope_size": ("Add a setting for the largest upload size allowed, 10 megabytes.", ["_MS"], []),
    "inverted": ("Add a setting for how long a login stays valid, 15 minutes.", ["milliseconds"], ["_MS"]),
}
WINDOW, RESERVE = 4096, 1024


def practise_case(exercise, requests, directory, seed):
    workspace = tasks.make_workspace(TASK, directory / "s2")
    tasks.apply_reference(TASK, "s2", workspace)
    for command in tasks.load_task(TASK).get("eval_setup", []):  # regenerate derived files, as a passing s2 leaves them
        code, out = tasks._run([sys.executable] + command.split()[1:], workspace, 60)
        if code != 0:
            raise RuntimeError(f"{command} failed: {out[-500:]}")
    practice = {"task_id": TASK, "request": requests[-1], "requests": requests, "max_steps": 20,
                "ws_before": workspace, "ws_after": workspace, "scratch": directory / "practice"}
    content = json.dumps({"exercises": [exercise]})

    def chat(messages, *args, **kwargs):
        if messages[-1]["content"].endswith(designs.DREAM_INSTRUCTION):
            return {"content": content, "tool_calls": [], "usage": {"prompt_tokens": 0, "completion_tokens": 0},
                    "seconds": 0.0, "finish_reason": "stop"}
        return llm.chat(messages, *args, **kwargs)

    cost = {"calls": 0, "prompt_tokens": 0, "completion_tokens": 0, "seconds": 0.0}
    items = [item.copy() for item in ITEMS]
    return designs._practise("dreaming", items, practice, chat, WINDOW, RESERVE, seed, cost)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--trials", type=int, default=3)
    parser.add_argument("--out", type=Path, default=Path("runs/adversarial-dreams"))
    args = parser.parse_args(argv)
    if not os.environ.get("DW_MODEL"):
        parser.error("set DW_MODEL to the model id served by the endpoint")
    if args.trials < 1:
        parser.error("--trials must be at least 1")

    requests = [session["prompt"] for session in tasks.load_task(TASK)["sessions"][:-1]]
    counts = {case: {"verified": 0, "changed": 0, "first": 0} for case in CASES}
    args.out.mkdir(parents=True, exist_ok=True)
    with (args.out / "results.jsonl").open("x", encoding="utf-8") as results:
        for trial in range(args.trials):
            seed = trial * run.SEED_STRIDE + run.SLEEP_OFFSET
            for case, (request, must_add, must_not_add) in CASES.items():
                exercise = {"decision": DECISION, "request": request, "must_add": must_add,
                            "must_not_add": must_not_add}
                directory = args.out / f"trial{trial}" / case
                items_after, record = practise_case(exercise, requests, directory, seed)
                changed = items_after != ITEMS
                row = {"case": case, "trial": trial, "record": record, "items_after": items_after, "changed": changed}
                results.write(json.dumps(row) + "\n")
                counts[case]["verified"] += any(dream["control_score"] == 0 for dream in record["dreams_offered"])
                counts[case]["changed"] += changed
                if case == "good" and record["exercises"]:
                    counts[case]["first"] += record["exercises"][0]["score"] == 0

    print("| Case | Trials | Control verified | Rules changed | First practice scored 0 |")
    print("|---|---:|---:|---:|---:|")
    for case, count in counts.items():
        first = count["first"] if case == "good" else "-"
        print(f"| {case} | {args.trials} | {count['verified']} | {count['changed']} | {first} |")


if __name__ == "__main__":
    main()
